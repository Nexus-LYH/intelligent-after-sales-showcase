CREATE TABLE tenant (
 id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
 code_normalized VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 name VARCHAR(100) NOT NULL,
 status TINYINT NOT NULL,
 security_epoch BIGINT NOT NULL DEFAULT 1,
 row_version BIGINT NOT NULL DEFAULT 0,
 created_at DATETIME(3) NOT NULL,
 updated_at DATETIME(3) NOT NULL,
 UNIQUE KEY uk_tenant_code (code_normalized),
 CONSTRAINT ck_tenant_code CHECK (CHAR_LENGTH(code_normalized) BETWEEN 2 AND 32 AND REGEXP_LIKE(code_normalized, '^[A-Z0-9_-]+$', 'c')),
 CONSTRAINT ck_tenant_name CHECK (CHAR_LENGTH(name) BETWEEN 2 AND 100),
 CONSTRAINT ck_tenant_state CHECK (status IN (0,1) AND security_epoch >= 1 AND row_version >= 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE identity_user (
 id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
 realm VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 tenant_id BIGINT NULL,
 login_namespace_id VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin
   GENERATED ALWAYS AS (CASE WHEN realm='PLATFORM' THEN 'PLATFORM' ELSE CONCAT('TENANT:',tenant_id) END) STORED,
 account_normalized VARCHAR(100) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 identity_type VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 display_name VARCHAR(50) NOT NULL,
 phone VARCHAR(30) NULL,
 department_id BIGINT NULL,
 password_verifier VARCHAR(512) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 status TINYINT NOT NULL DEFAULT 0,
 must_change_password TINYINT NOT NULL DEFAULT 1,
 binding_state TINYINT NOT NULL,
 security_version BIGINT NOT NULL DEFAULT 1,
 row_version BIGINT NOT NULL DEFAULT 0,
 created_at DATETIME(3) NOT NULL,
 updated_at DATETIME(3) NOT NULL,
 UNIQUE KEY uk_user_account (login_namespace_id,account_normalized),
 KEY ix_user_tenant (tenant_id),
 CONSTRAINT fk_user_tenant FOREIGN KEY (tenant_id) REFERENCES tenant(id) ON DELETE RESTRICT,
 CONSTRAINT ck_user_identity CHECK ((realm='PLATFORM' AND tenant_id IS NULL AND identity_type='PLATFORM') OR (realm='TENANT' AND tenant_id IS NOT NULL AND identity_type IN ('EMPLOYEE','CUSTOMER'))),
 CONSTRAINT ck_user_account CHECK (CHAR_LENGTH(account_normalized) BETWEEN 1 AND 100 AND REGEXP_LIKE(account_normalized, '^[a-z0-9._-]+$', 'c')),
 CONSTRAINT ck_user_profile CHECK (CHAR_LENGTH(display_name) BETWEEN 1 AND 50 AND (phone IS NULL OR CHAR_LENGTH(phone) BETWEEN 1 AND 30) AND (department_id IS NULL OR (identity_type='EMPLOYEE' AND department_id>0))),
 CONSTRAINT ck_user_binding CHECK ((identity_type='CUSTOMER' AND binding_state IN (1,2)) OR (identity_type IN ('EMPLOYEE','PLATFORM') AND binding_state=0)),
 CONSTRAINT ck_user_state CHECK (status IN (0,1) AND must_change_password IN (0,1) AND security_version>=1 AND row_version>=0 AND CHAR_LENGTH(password_verifier)>0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE identity_session_context (
 id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
 token_hash BINARY(32) NOT NULL,
 kind VARCHAR(8) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 user_id BIGINT NULL,
 tenant_id BIGINT NULL,
 access_state VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NULL,
 issued_user_security_version BIGINT NULL,
 issued_tenant_security_epoch BIGINT NULL,
 issued_at DATETIME(3) NOT NULL,
 expires_at DATETIME(3) NOT NULL,
 preauth_state VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NULL,
 consumed_at DATETIME(3) NULL,
 delivery_state VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NULL,
 delivery_confirm_deadline DATETIME(3) NULL,
 confirmed_at DATETIME(3) NULL,
 revoked_at DATETIME(3) NULL,
 revoke_reason_code VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NULL,
 csrf_token VARCHAR(43) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 login_attempt_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL,
 row_version BIGINT NOT NULL DEFAULT 0,
 updated_at DATETIME(3) NOT NULL,
 UNIQUE KEY uk_context_token (token_hash),
 UNIQUE KEY uk_context_attempt (login_attempt_id),
 KEY ix_context_user (user_id,issued_at,id),
 KEY ix_context_expiry (expires_at),
 CONSTRAINT fk_context_user FOREIGN KEY (user_id) REFERENCES identity_user(id) ON DELETE RESTRICT,
 CONSTRAINT fk_context_tenant FOREIGN KEY (tenant_id) REFERENCES tenant(id) ON DELETE RESTRICT,
 CONSTRAINT ck_context_kind CHECK (
  (kind='PREAUTH' AND user_id IS NULL AND tenant_id IS NULL AND access_state IS NULL AND issued_user_security_version IS NULL AND issued_tenant_security_epoch IS NULL AND preauth_state IS NOT NULL AND preauth_state IN ('READY','PROCESSING','FAILED','CONSUMED') AND delivery_state IS NULL AND delivery_confirm_deadline IS NULL AND confirmed_at IS NULL AND login_attempt_id IS NULL)
  OR (kind='AUTH' AND user_id IS NOT NULL AND access_state IS NOT NULL AND access_state IN ('NORMAL','PASSWORD_CHANGE_REQUIRED') AND issued_user_security_version IS NOT NULL AND issued_user_security_version>=1 AND preauth_state IS NULL AND consumed_at IS NULL AND delivery_state IS NOT NULL AND delivery_state IN ('UNCONFIRMED','CONFIRMED') AND delivery_confirm_deadline IS NOT NULL AND login_attempt_id IS NOT NULL AND ((tenant_id IS NULL AND issued_tenant_security_epoch IS NULL) OR (tenant_id IS NOT NULL AND issued_tenant_security_epoch IS NOT NULL AND issued_tenant_security_epoch>=1)))
 ),
 CONSTRAINT ck_context_expiry CHECK (expires_at>issued_at AND row_version>=0 AND (delivery_confirm_deadline IS NULL OR (delivery_confirm_deadline>issued_at AND delivery_confirm_deadline<=expires_at))),
 CONSTRAINT ck_context_consumed CHECK ((preauth_state='CONSUMED' AND consumed_at IS NOT NULL) OR (consumed_at IS NULL AND (preauth_state IS NULL OR preauth_state<>'CONSUMED'))),
 CONSTRAINT ck_context_confirmation CHECK ((delivery_state='CONFIRMED' AND confirmed_at IS NOT NULL AND confirmed_at>=issued_at AND confirmed_at<delivery_confirm_deadline) OR (confirmed_at IS NULL AND (delivery_state IS NULL OR delivery_state='UNCONFIRMED'))),
 CONSTRAINT ck_context_revocation CHECK ((revoked_at IS NULL AND revoke_reason_code IS NULL) OR (revoked_at IS NOT NULL AND revoke_reason_code IS NOT NULL)),
 CONSTRAINT ck_context_csrf CHECK (CHAR_LENGTH(csrf_token)=43 AND REGEXP_LIKE(csrf_token,'^[A-Za-z0-9_-]+$','c'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE identity_login_attempt (
 attempt_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL PRIMARY KEY,
 preauth_context_id BIGINT NOT NULL,
 expected_realm VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 expected_tenant_code_normalized VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NULL,
 expected_account_normalized VARCHAR(100) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 status VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 failure_code VARCHAR(48) CHARACTER SET ascii COLLATE ascii_bin NULL,
 created_at DATETIME(3) NOT NULL,
 completed_at DATETIME(3) NULL,
 retain_until DATETIME(3) NOT NULL,
 row_version BIGINT NOT NULL DEFAULT 0,
 UNIQUE KEY uk_attempt_preauth (preauth_context_id),
 KEY ix_attempt_retention (retain_until),
 CONSTRAINT fk_attempt_preauth FOREIGN KEY (preauth_context_id) REFERENCES identity_session_context(id) ON DELETE RESTRICT,
 CONSTRAINT ck_attempt_id CHECK (REGEXP_LIKE(attempt_id,'^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$','c')),
 CONSTRAINT ck_attempt_location CHECK ((expected_realm='PLATFORM' AND expected_tenant_code_normalized IS NULL) OR (expected_realm='TENANT' AND expected_tenant_code_normalized IS NOT NULL AND CHAR_LENGTH(expected_tenant_code_normalized) BETWEEN 2 AND 32 AND REGEXP_LIKE(expected_tenant_code_normalized,'^[A-Z0-9_-]+$','c'))),
 CONSTRAINT ck_attempt_account CHECK (CHAR_LENGTH(expected_account_normalized) BETWEEN 1 AND 100 AND REGEXP_LIKE(expected_account_normalized,'^[a-z0-9._-]+$','c')),
 CONSTRAINT ck_attempt_state CHECK ((status='PROCESSING' AND completed_at IS NULL AND failure_code IS NULL) OR (status='FAILED' AND completed_at IS NOT NULL AND failure_code IS NOT NULL) OR (status='ISSUED' AND completed_at IS NOT NULL AND failure_code IS NULL)),
 CONSTRAINT ck_attempt_time CHECK (retain_until>=created_at AND (completed_at IS NULL OR completed_at>=created_at) AND row_version>=0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

ALTER TABLE identity_session_context ADD CONSTRAINT fk_context_attempt FOREIGN KEY (login_attempt_id) REFERENCES identity_login_attempt(attempt_id) ON DELETE RESTRICT;

CREATE TABLE identity_revocation_operation (
 operation_id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
 actor_user_id BIGINT NOT NULL,
 actor_namespace_id VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 operation_type VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 idempotency_key VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 target_user_id BIGINT NOT NULL,
 request_digest BINARY(32) NOT NULL,
 digest_schema_version TINYINT NOT NULL DEFAULT 1,
 expected_security_version BIGINT NOT NULL,
 new_security_version BIGINT NOT NULL,
 reason VARCHAR(200) NOT NULL,
 scope VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 result_code VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 revoked_at DATETIME(3) NOT NULL,
 trace_id VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 UNIQUE KEY uk_operation_key (actor_namespace_id,actor_user_id,operation_type,idempotency_key),
 KEY ix_operation_target (target_user_id,revoked_at,operation_id),
 CONSTRAINT fk_operation_actor FOREIGN KEY (actor_user_id) REFERENCES identity_user(id) ON DELETE RESTRICT,
 CONSTRAINT fk_operation_target FOREIGN KEY (target_user_id) REFERENCES identity_user(id) ON DELETE RESTRICT,
 CONSTRAINT ck_operation_key CHECK (CHAR_LENGTH(idempotency_key) BETWEEN 1 AND 128 AND REGEXP_LIKE(idempotency_key,'^[!-~]+$','c')),
 CONSTRAINT ck_operation_result CHECK (operation_type='USER_SESSIONS_REVOKE' AND scope='ALL_SESSIONS' AND result_code='REVOKED' AND expected_security_version>=1 AND new_security_version=expected_security_version+1 AND digest_schema_version>=1 AND CHAR_LENGTH(reason) BETWEEN 5 AND 200)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE identity_security_audit (
 id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
 occurred_at DATETIME(3) NOT NULL,
 action VARCHAR(48) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 actor_type VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 actor_user_id BIGINT NULL,
 actor_namespace_id VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NULL,
 target_type VARCHAR(24) CHARACTER SET ascii COLLATE ascii_bin NULL,
 target_id BIGINT NULL,
 tenant_id BIGINT NULL,
 result VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 reason_code VARCHAR(48) CHARACTER SET ascii COLLATE ascii_bin NULL,
 reason VARCHAR(200) NULL,
 user_security_version_before BIGINT NULL,
 user_security_version_after BIGINT NULL,
 tenant_security_epoch_before BIGINT NULL,
 tenant_security_epoch_after BIGINT NULL,
 login_attempt_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL,
 revocation_operation_id BIGINT NULL,
 trace_id VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 source_ip_masked VARCHAR(64) NULL,
 user_agent_summary VARCHAR(256) NULL,
 KEY ix_audit_tenant (tenant_id,occurred_at,id),
 KEY ix_audit_trace (trace_id),
 KEY ix_audit_operation (revocation_operation_id),
 CONSTRAINT fk_audit_operation FOREIGN KEY (revocation_operation_id) REFERENCES identity_revocation_operation(operation_id) ON DELETE RESTRICT,
 CONSTRAINT ck_audit_actor CHECK (actor_type IN ('USER','ANONYMOUS','SYSTEM') AND ((actor_type='USER' AND actor_user_id IS NOT NULL AND actor_namespace_id IS NOT NULL) OR (actor_type<>'USER' AND actor_user_id IS NULL))),
 CONSTRAINT ck_audit_result CHECK (result IN ('SUCCESS','DENIED','FAILURE','UNKNOWN')),
 CONSTRAINT ck_audit_target CHECK ((target_type IS NULL AND target_id IS NULL) OR (target_type IS NOT NULL AND target_id IS NOT NULL)),
 CONSTRAINT ck_audit_user_version CHECK ((user_security_version_before IS NULL AND user_security_version_after IS NULL) OR (user_security_version_before IS NOT NULL AND user_security_version_after IS NOT NULL AND user_security_version_before>=1 AND user_security_version_after>=user_security_version_before)),
 CONSTRAINT ck_audit_tenant_version CHECK ((tenant_security_epoch_before IS NULL AND tenant_security_epoch_after IS NULL) OR (tenant_security_epoch_before IS NOT NULL AND tenant_security_epoch_after IS NOT NULL AND tenant_security_epoch_before>=1 AND tenant_security_epoch_after>=tenant_security_epoch_before))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
